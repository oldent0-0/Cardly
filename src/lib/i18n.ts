export function translateError(error: unknown, t: Translate, fallback: TranslationKey) {
  if (error instanceof Error) {
    const key = apiErrorKeys[error.message]
    if (key) return t(key)
    if (error.name === 'ApiError' && 'status' in error && typeof error.status === 'number') {
      if (error.status === 400) return t('checkInformation')
      if (error.status >= 500) return t('serverTryAgain')
      return error.message
    }
    if (error instanceof TypeError) return t('apiUnavailable')
  }
  return t(fallback)
}
