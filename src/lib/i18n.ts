export type Translate = (key: TranslationKey, values?: Record<string, string | number>) => string

export const LocaleContext = createContext<{ language: Language; setLanguage: (language: Language) => void; t: Translate } | null>(null)

export function useLocale() {
  const locale = useContext(LocaleContext)
  if (!locale) throw new Error('Language context is not available.')
  return locale
}

export function translate(language: Language, key: TranslationKey, values?: Record<string, string | number>) {
  const template = (language === 'mn' ? mn : en)[key]
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(values?.[name] ?? `{${name}}`))
}

